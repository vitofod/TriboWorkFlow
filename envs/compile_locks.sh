#!/usr/bin/env bash
# Regenerate the lock files of the historic and the development environment.
#
# Usage (from any directory):  bash envs/compile_locks.sh
# Requires uv (UV=/path/to/uv to use one not on PATH). See envs/README.md.
set -euo pipefail

UV=${UV:-uv}
ENVS=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$ENVS/.."

# Release dates of the upper bounds in TribChem's requirements.txt fall
# between 2024-07-09 (setuptools 70.3.0) and 2024-07-16; setuptools 71.0.0
# and pymatgen 2024.7.18 came out on 2024-07-17 and 2024-07-18.
CUTOFF=2024-07-17T00:00:00Z
# ASE 3.26.0 was uploaded on 2025-08-12.
ASE_CUTOFF=2025-08-13T00:00:00Z

"$UV" pip compile envs/historic/requirements.in \
    --python-version 3.12.4 \
    --exclude-newer "$CUTOFF" \
    --generate-hashes \
    --custom-compile-command "bash envs/compile_locks.sh" \
    --quiet \
    --output-file envs/historic/requirements.lock

# The development environment is constrained to the historic versions,
# except for ASE.
constraints=envs/dev/historic-constraints.txt
{
    echo "# Generated by envs/compile_locks.sh from envs/historic/requirements.lock"
    echo "# (all pins except ase). Do not edit."
    grep -E '^[A-Za-z0-9_.-]+==' envs/historic/requirements.lock \
        | sed 's/ .*//' | grep -v '^ase=='
} > "$constraints"

"$UV" pip compile envs/dev/requirements.in \
    --python-version 3.12 \
    --constraint "$constraints" \
    --exclude-newer "$CUTOFF" \
    --exclude-newer-package "ase=$ASE_CUTOFF" \
    --generate-hashes \
    --custom-compile-command "bash envs/compile_locks.sh" \
    --quiet \
    --output-file envs/dev/requirements.lock

echo "historic: $(grep -cE '^[A-Za-z0-9_.-]+==' envs/historic/requirements.lock) packages"
echo "dev:      $(grep -cE '^[A-Za-z0-9_.-]+==' envs/dev/requirements.lock) packages"
